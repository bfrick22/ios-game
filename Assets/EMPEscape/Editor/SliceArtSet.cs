using UnityEngine;

namespace EMPEscape.EditorTools
{
    /// <summary>
    /// Which models the test-slice builder uses. Empty slots fall back to grey placeholder shapes.
    /// The builder auto-fills empty slots from Assets/EMPEscape/Art/* by file name, so you only
    /// touch this asset (Assets/EMPEscape/Art/SliceArtSet.asset) to override a pick.
    /// </summary>
    [CreateAssetMenu(menuName = "EMP Escape/Slice Art Set", fileName = "SliceArtSet")]
    public class SliceArtSet : ScriptableObject
    {
        [Header("Characters (Mixamo-rigged FBX in Art/Characters)")]
        public GameObject player;
        public GameObject ray;
        [Tooltip("Generated by EMP Escape > Build Character Animator from clips in Art/Animations.")]
        public RuntimeAnimatorController characterAnimator;
        [Tooltip("Extra Y rotation if character models face away from their walk direction.")]
        public float characterYawOffset;

        [Header("Vehicles (Kenney Car Kit FBX in Art/Vehicles)")]
        public GameObject yourCar;
        public GameObject[] parkedCars = new GameObject[0];
        public GameObject van;
        public GameObject truck;
        [Tooltip("Extra Y rotation if vehicle models point sideways or backwards.")]
        public float vehicleYawOffset;

        [Header("Weapons (optional models in Art/Weapons; empty = simple shapes)")]
        public GameObject knife;
        public GameObject bat;
        public GameObject pistol;
        [Tooltip("Weapon offset in the right-hand bone's space. Tune on the Player's WeaponHolder in Play mode, then copy here.")]
        public Vector3 weaponGripPosition;
        public Vector3 weaponGripRotation;

        [Header("City backdrop (Kenney City Kit FBX in Art/City)")]
        public GameObject[] buildings = new GameObject[0];
        public GameObject[] streetProps = new GameObject[0];
    }
}
